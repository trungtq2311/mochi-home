// Calibrate move counts so every level hits a target win rate for the casual bot.
// Run: node src/sim/calibrate.ts [maxLevel] [runs]   → rewrites src/match3/tuning.ts
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../match3/levels.ts';
import { playOnce } from './bot.ts';

const maxLevel = Number(process.argv[2] ?? 200);
const runs = Number(process.argv[3] ?? 80);

/** Target bot win rate: a gentle sawtooth inside every block of 10, hard levels (x0) a bit tougher. */
function target(n: number): number {
  if (n <= 6) return 0.98;
  if (n % 10 === 0) return 0.7;
  const k = n % 10; // 1..9
  return 0.96 - (k / 9) * 0.12; // 96% right after a hard level → 84% just before the next one
}

const out: Record<number, [number, number]> = {};
for (let n = 1; n <= maxLevel; n++) {
  let chosen: [number, number] | null = null;
  for (let variant = 0; variant < 6 && !chosen; variant++) {
    const level = generateLevel(n, variant);
    const used: number[] = [];
    for (let i = 0; i < runs; i++) {
      const r = playOnce(level, 90000 + n * 1000 + i * 13, true);
      used.push(r.won ? r.movesUsed : 999);
    }
    used.sort((a, b) => a - b);
    const moves = used[Math.min(runs - 1, Math.ceil(target(n) * runs) - 1)];
    // Too long (or unwinnable) → try another layout of the same level.
    // New players get plenty of room on the first levels.
    if (moves <= 40 || variant === 5) chosen = [variant, Math.max(n <= 10 ? 20 : 15, Math.min(45, moves))];
  }
  out[n] = chosen!;
  if (n % 10 === 0) console.log(`level ${n}: variant ${chosen![0]}, ${chosen![1]} moves`);
}

const body = Object.entries(out).map(([n, [v, m]]) => `  ${n}: [${v}, ${m}],`).join('\n');
writeFileSync(
  new URL('../match3/tuning.ts', import.meta.url),
  `// Generated by \`node src/sim/calibrate.ts\`. [layoutVariant, moves] per level.\nexport const TUNING: Record<number, [number, number]> = {\n${body}\n};\n`,
);
console.log('wrote tuning.ts');
